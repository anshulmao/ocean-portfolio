import assert from 'node:assert/strict';
import {bindHeldMap} from '../ocean-refined/held-map.js';
const listeners = {};
const window = {addEventListener: (type, fn) => {listeners[type] = fn;}};
const document = {hidden: false, addEventListener: window.addEventListener};
let expanded = false, available = true;
bindHeldMap({window, document, available: () => available, getExpanded: () => expanded, setExpanded: value => {expanded = value;}});
const key = (type, code, extra = {}) => listeners[type]({code, target: {closest: () => false}, preventDefault() {}, ...extra});
key('keydown', 'KeyM'); assert.ok(expanded);
key('keydown', 'CapsLock'); key('keyup', 'KeyM'); assert.ok(expanded, 'either held shortcut keeps map open');
key('keyup', 'CapsLock'); assert.ok(!expanded, 'release restores minimap');
expanded = true; key('keydown', 'KeyM'); key('keyup', 'KeyM'); assert.ok(expanded, 'preserve manually expanded map');
expanded = false; key('keydown', 'CapsLock'); listeners.blur(); assert.ok(!expanded, 'blur clears held shortcuts');
key('keydown', 'KeyM'); document.hidden = true; listeners.visibilitychange(); assert.ok(!expanded);
key('keydown', 'KeyM'); listeners.oceanmediumchange(); assert.ok(!expanded);
available = false; key('keydown', 'KeyM'); assert.ok(!expanded, 'surface and overlays ignore shortcut');
available = true; key('keydown', 'KeyM', {target: {closest: () => true}}); assert.ok(!expanded, 'typing is unaffected');
key('keydown', 'KeyM', {repeat: true}); assert.ok(!expanded, 'repeats cannot reopen the map');
console.log('Held map shortcuts passed');
