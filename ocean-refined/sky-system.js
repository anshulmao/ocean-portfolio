// Astronomy HOR axes are North, West, Zenith. World axes are South, Up, West:
// initial camera forward -Z therefore faces East; north is to the viewer's left.
function horizontalWorld(vector,target=new THREE.Vector3()) {
  return target.set(-vector.x,vector.z,vector.y).normalize();
}
function catalogWorldRotation(rotation,target) {
  const r=rotation.rot;
  target.makeBasis(new THREE.Vector3(r[1][0],-r[1][2],-r[1][1]),
    new THREE.Vector3(-r[2][0],r[2][2],r[2][1]),new THREE.Vector3(r[0][0],-r[0][2],-r[0][1]));
  return target;
}

const lineVertex = /* glsl */ `
  varying float vHorizon;
  void main() {
    vHorizon=normalize((modelMatrix*vec4(position,0.0)).xyz).y;
    gl_Position=(projectionMatrix*modelViewMatrix*vec4(position,1.0)).xyww;
  }
`;
const lineFragment = /* glsl */ `
  uniform float uNight;uniform float uDive;uniform vec4 uWeather;varying float vHorizon;
  void main() {
    float a=smoothstep(.0,.09,vHorizon)*smoothstep(.38,.92,uNight)*(1.0-uDive)*(1.0-smoothstep(.08,.55,uWeather.w))*.21;
    gl_FragColor=vec4(.46,.67,.86,a);
  }
`;

export function createSkySystem(uniforms, rng) {
  const root = new THREE.Group(); root.name = 'Moving celestial sphere';
  weatherUniforms(uniforms);
  // The dome has a program per medium (see skyFragment). The two it is not using
  // ride along on hidden meshes, so the start-up compile builds all three and
  // crossing the surface never waits for a shader.
  const domeMaterial=defines=>new THREE.ShaderMaterial({uniforms,defines,vertexShader:skyVertex,fragmentShader:skyFragment,side:THREE.BackSide,depthWrite:false,fog:false});
  const domes={above:domeMaterial({SKY_ABOVE:1}),between:domeMaterial({}),below:domeMaterial({SKY_BELOW:1})};
  const shell = new THREE.Mesh(new THREE.SphereGeometry(850,40,24),domes.above);
  shell.renderOrder=-100;shell.frustumCulled=false;root.add(shell);
  for(const material of [domes.between,domes.below]){const spare=new THREE.Mesh(shell.geometry,material);spare.visible=false;spare.name='Sky program warm-up';root.add(spare);}
  // The slow-varying sky, baked for the dome, the sea's reflection and Snell's window (see shaders.js).
  // Half floats where the GPU can render to them; the square-root encoding keeps 8 bits usable otherwise.
  const skyTarget=new THREE.WebGLRenderTarget(SKY_MAP,SKY_MAP,{type:THREE.HalfFloatType,depthBuffer:false,generateMipmaps:false,minFilter:THREE.LinearFilter,magFilter:THREE.LinearFilter});
  skyTarget.texture.name='Baked sky';uniforms.uSkyMap.value=skyTarget.texture;
  const bakeScene=new THREE.Scene(),bakeCamera=new THREE.Camera(),bakeGeometry=new THREE.BufferGeometry();
  bakeGeometry.setAttribute('position',new THREE.Float32BufferAttribute([-1,-1,0,3,-1,0,-1,3,0],3));
  const bakeMesh=new THREE.Mesh(bakeGeometry,new THREE.ShaderMaterial({uniforms,vertexShader:skyMapVertex,fragmentShader:skyMapFragment,depthTest:false,depthWrite:false,fog:false}));
  bakeMesh.frustumCulled=false;bakeScene.add(bakeMesh);
  // The baked sky drifts by a fraction of a texel a frame, so it is refreshed every third frame; urgent (lightning, a time or weather change under way) refreshes at once.
  let bakeChecked=false,bakeIn=0;
  const checkTarget=renderer=>{if(!bakeChecked){bakeChecked=true;const extensions=renderer.extensions;if(!extensions.has('EXT_color_buffer_float')&&!extensions.has('EXT_color_buffer_half_float'))skyTarget.texture.type=THREE.UnsignedByteType;}};
  // Hands the bake's program to the browser ahead of the first bake, built for the target it draws into, so that bake does not wait on a compile. Returns its materials.
  function prepare(renderer) {
    checkTarget(renderer);
    const target=renderer.getRenderTarget();
    renderer.setRenderTarget(skyTarget);const materials=renderer.compile(bakeScene,bakeCamera);renderer.setRenderTarget(target);
    return materials;
  }
  function bake(renderer,urgent=false) {
    if(--bakeIn>0&&!urgent)return;bakeIn=3;
    checkTarget(renderer);
    const target=renderer.getRenderTarget();
    renderer.setRenderTarget(skyTarget);renderer.render(bakeScene,bakeCamera);renderer.setRenderTarget(target);
  }

  // One rigid observer transform rotates every catalog star and guide together.
  const horizon = new THREE.Group();
  const celestial = new THREE.Group();horizon.add(celestial);root.add(horizon);
  const coords=[],sizes=[],seeds=[],colors=[],positions=new Map();
  const notable=new Set(PATTERNS.flatMap(pattern=>pattern.ids));
  for(const [hr,ra,dec,mag] of CATALOG) {
    const p=equatorial(ra,dec);positions.set(hr,p);coords.push(...p.toArray());
    sizes.push(Math.min(5.5,(notable.has(hr)?2.1:1.1)+Math.max(0,5-mag)*.49));
    seeds.push(rng()*Math.PI*2);
    // Gentle color variation is decorative; Betelgeuse, Antares and Gacrux are red giants.
    if(hr===2061||hr===6134||hr===4763)colors.push(1,.70,.48);
    else colors.push(.72+rng()*.16,.83+rng()*.10,1);
  }
  const geo=new THREE.BufferGeometry();
  geo.setAttribute('position',new THREE.Float32BufferAttribute(coords,3));
  geo.setAttribute('aSize',new THREE.Float32BufferAttribute(sizes,1));
  geo.setAttribute('aSeed',new THREE.Float32BufferAttribute(seeds,1));
  geo.setAttribute('aColor',new THREE.Float32BufferAttribute(colors,3));
  const stars=new THREE.Points(geo,new THREE.ShaderMaterial({uniforms,vertexShader:starsVertex,fragmentShader:starsFragment,
    transparent:true,depthWrite:false,fog:false,blending:THREE.AdditiveBlending}));
  stars.renderOrder=-90;stars.frustumCulled=false;celestial.add(stars);

  const linePositions=[],labels=[];
  for(const pattern of PATTERNS) {
    for(const [a,b] of pattern.edges)linePositions.push(...positions.get(a).toArray(),...positions.get(b).toArray());
    const anchor=new THREE.Object3D();anchor.name=pattern.name;
    for(const id of pattern.ids)anchor.position.add(positions.get(id));
    anchor.position.normalize().multiplyScalar(680);celestial.add(anchor);labels.push({name:pattern.name,anchor});
  }
  const lineGeo=new THREE.BufferGeometry();lineGeo.setAttribute('position',new THREE.Float32BufferAttribute(linePositions,3));
  const lines=new THREE.LineSegments(lineGeo,new THREE.ShaderMaterial({uniforms,vertexShader:lineVertex,fragmentShader:lineFragment,
    transparent:true,depthWrite:false,fog:false,blending:THREE.AdditiveBlending}));
  lines.renderOrder=-89;lines.frustumCulled=false;celestial.add(lines);

  const observer=new Astronomy.Observer(OBSERVER.latitude,OBSERVER.longitude,OBSERVER.elevation);
  const now=new Date(),localDate=new Date(now.getTime()+8*3600000);
  const localMidnight=new Date(Date.UTC(localDate.getUTCFullYear(),localDate.getUTCMonth(),localDate.getUTCDate())-8*3600000);
  const reference=Astronomy.SearchHourAngle(Astronomy.Body.Sun,observer,24-70/15,localMidnight).time.date;
  const initialPhase=(now-reference)/DAY_MS*TAU;
  // Presets use this date's actual rising/setting sun, not fabricated directions.
  const sunrise=Astronomy.SearchAltitude(Astronomy.Body.Sun,observer,1,localMidnight,1,2);
  const sunset=Astronomy.SearchAltitude(Astronomy.Body.Sun,observer,-1,localMidnight,1,2);
  const presets={day:0,night:Math.PI,
    dawn:(sunrise.date-reference)/DAY_MS*TAU,
    dusk:(sunset.date-reference)/DAY_MS*TAU};
  // Begin just before sunrise on the current local date, keeping the real sky.
  const openingPhase=presets.dawn-12*60*1000/DAY_MS*TAU;
  const rotationMatrix=new THREE.Matrix4(),sunDirection=new THREE.Vector3(),moonDirection=new THREE.Vector3(),moonLight=new THREE.Vector3();
  let cachedPhase=NaN,cachedState,turnedFor=null;
  const atPhase=phase=>new Date(reference.getTime()+phase/TAU*DAY_MS);
  function skyState(phase) {
    if(phase===cachedPhase)return cachedState;
    const date=atPhase(phase),time=Astronomy.MakeTime(date);
    const sun=Astronomy.Equator(Astronomy.Body.Sun,time,observer,true,true);
    const moon=Astronomy.Equator(Astronomy.Body.Moon,time,observer,true,true);
    const horizontal=Astronomy.Rotation_EQD_HOR(time,observer);
    horizontalWorld(Astronomy.RotateVector(horizontal,sun.vec),sunDirection);
    horizontalWorld(Astronomy.RotateVector(horizontal,moon.vec),moonDirection);
    const light=new Astronomy.Vector(sun.vec.x-moon.vec.x,sun.vec.y-moon.vec.y,sun.vec.z-moon.vec.z,time);
    horizontalWorld(Astronomy.RotateVector(horizontal,light),moonLight);
    const altitude=THREE.MathUtils.radToDeg(Math.asin(THREE.MathUtils.clamp(sunDirection.y,-1,1)));
    const illumination=Astronomy.Illumination(Astronomy.Body.Moon,time);
    cachedState={date,time,sunDirection:sunDirection.toArray(),night:1-THREE.MathUtils.smoothstep(altitude,-6,4),sunAltitude:altitude,
      moonAltitude:THREE.MathUtils.radToDeg(Math.asin(THREE.MathUtils.clamp(moonDirection.y,-1,1))),
      moonIllumination:illumination.phase_fraction,moonPhaseAngle:Astronomy.MoonPhase(time),
      sunRA:sun.ra,sunDec:sun.dec,moonRA:moon.ra,moonDec:moon.dec,
      simulatedUTC:date.toISOString(),
      observer:OBSERVER,acceleration:72};
    cachedPhase=phase;return cachedState;
  }
  // True ecliptic-of-date guide, represented in the same J2000 frame as catalog stars.
  // Earth obliquity is approximately 23.44 degrees, not an arbitrary screen curve:
  // https://nssdc.gsfc.nasa.gov/planetary/factsheet/earthfact.html
  const eclipticRotation=Astronomy.Rotation_ECT_EQJ(now),guideCoords=[];
  const equatorRotation=Astronomy.Rotation_EQD_EQJ(now);
  const asCatalog=v=>new THREE.Vector3(-v.y,v.z,-v.x).normalize().multiplyScalar(678);
  function eclipticPoint(angle) {
    return asCatalog(Astronomy.RotateVector(eclipticRotation,new Astronomy.Vector(Math.cos(angle),Math.sin(angle),0,now)));
  }
  function equatorPoint(angle,declination=0){
    const c=Math.cos(declination);
    return asCatalog(Astronomy.RotateVector(equatorRotation,new Astronomy.Vector(c*Math.cos(angle),c*Math.sin(angle),Math.sin(declination),now)));
  }
  for(let i=0;i<180;i++)guideCoords.push(...eclipticPoint(i/180*TAU).toArray(),...eclipticPoint((i+1)/180*TAU).toArray());
  for(let i=0;i<180;i++)guideCoords.push(...equatorPoint(i/180*TAU).toArray(),...equatorPoint((i+1)/180*TAU).toArray());
  const lunarPath=[];
  for(let i=0;i<=96;i++){
    const date=new Date(now.getTime()+i/96*27.321661*DAY_MS);
    lunarPath.push(asCatalog(Astronomy.GeoVector(Astronomy.Body.Moon,date,true)));
  }
  for(let i=0;i<96;i++)guideCoords.push(...lunarPath[i].toArray(),...lunarPath[i+1].toArray());
  const guideGeo=new THREE.BufferGeometry();guideGeo.setAttribute('position',new THREE.Float32BufferAttribute(guideCoords,3));
  const guides=new THREE.LineSegments(guideGeo,new THREE.ShaderMaterial({uniforms,vertexShader:lineVertex,
    fragmentShader:lineFragment.replace('*.21','*.095').replace('vec4(.46,.67,.86,a)','vec4(.58,.54,.38,a)'),
    transparent:true,depthWrite:false,fog:false,blending:THREE.AdditiveBlending}));
  guides.renderOrder=-88;guides.frustumCulled=false;celestial.add(guides);
  guides.name='Ecliptic, equator and projected lunar path';
  function addGuideLabel(name,position) {
    const anchor=new THREE.Object3D();anchor.name=name;anchor.position.copy(position);celestial.add(anchor);labels.push({name,anchor,kind:'guide'});
  }
  addGuideLabel('Ecliptic · Sun’s annual path',eclipticPoint(Math.PI/3));
  addGuideLabel('Moon · projected 27-day path',lunarPath[30]);
  addGuideLabel('Celestial equator',equatorPoint(300*Math.PI/180));
  addGuideLabel('North celestial pole · 3.14° above north',equatorPoint(0,Math.PI/2));
  addGuideLabel('South celestial pole',equatorPoint(0,-Math.PI/2));
  const eclipticNorth=asCatalog(Astronomy.RotateVector(eclipticRotation,new Astronomy.Vector(0,0,1,now)));
  addGuideLabel('North ecliptic pole',eclipticNorth);
  addGuideLabel('South ecliptic pole',eclipticNorth.clone().negate());
  const galacticPole=equatorial(192.85948,27.12825,1);
  // IAU galactic pole J2000 orientation, for the rotating broad Milky Way band:
  // https://www.aanda.org/articles/aa/pdf/2020/09/aa38291-20.pdf (Appendix A)
  uniforms.uMilkyWay ??= {value:new THREE.Vector3()};
  uniforms.uMoonLight ??= {value:new THREE.Vector3()};
  uniforms.uMoonFraction ??= {value:0};
  function update(phase,cameraPosition,night,underwater,elapsed) {
    const state=skyState(phase);
    root.position.copy(cameraPosition);
    uniforms.uSun.value.copy(sunDirection);uniforms.uMoon.value.copy(moonDirection);uniforms.uMoonLight.value.copy(moonLight);
    uniforms.uMoonFraction.value=state.moonIllumination;
    // The star sphere only turns when the clock has moved.
    if(state!==turnedFor){turnedFor=state;catalogWorldRotation(Astronomy.Rotation_EQJ_HOR(state.time,observer),rotationMatrix);horizon.quaternion.setFromRotationMatrix(rotationMatrix);}
    uniforms.uMilkyWay.value.copy(galacticPole).applyQuaternion(horizon.quaternion);
    uniforms.uTime.value=elapsed;uniforms.uNight.value=night;uniforms.uDive.value=underwater;
    const dome=underwater<=0?domes.above:underwater>=.999?domes.below:domes.between;if(shell.material!==dome)shell.material=dome;
    celestial.visible=night>.001&&underwater<.995;
    root.updateMatrixWorld(true);
    return state;
  }
  return {root,update,bake,prepare,labels,starCount:CATALOG.length,constellationCount:PATTERNS.length,
    initialPhase,openingPhase,presets,referenceUTC:reference.toISOString(),observer:OBSERVER,
    getNightFactor:phase=>skyState(phase).night,getState:skyState};
}
