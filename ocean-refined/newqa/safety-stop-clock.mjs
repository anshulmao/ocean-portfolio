import assert from 'node:assert/strict';
import { createSafetyStopClock, inSafetyStopRange } from '../safety-stop-clock.js';
for(const depth of [3,3.5,4,5]) assert.equal(inSafetyStopRange(depth),true);
for(const depth of [2.999,5.001,6,NaN,Infinity]) assert.equal(inSafetyStopRange(depth),false);
const clock = createSafetyStopClock();
clock.start();
assert.equal(clock.remaining,45);
assert.equal(clock.advance(44.9),false);
assert.ok(clock.remaining>.09);
assert.equal(clock.advance(.11),true);
assert.equal(clock.remaining,0);
assert.equal(clock.advance(1),false,'Completion must fire once');
assert.equal(clock.completed,true);
clock.start();clock.advance(5);clock.cancel();clock.advance(100);
assert.equal(clock.remaining,40,'Cancellation stops the countdown without marking completion');
assert.equal(clock.completed,false);
clock.start();clock.advance(NaN);clock.advance(-1);
assert.equal(clock.remaining,45);
for(let i=0;i<450;i++)clock.advance(.1);
assert.ok(clock.remaining<1e-9);
assert.equal(clock.completed,true,'Exactly 45 seconds completes even with fractional frame steps');
clock.start();clock.advance(10);clock.pause();
assert.equal(clock.paused,true);
assert.equal(clock.advance(100),false,'Feedback pauses cannot finish the stop');
assert.equal(clock.remaining,35);
clock.resume();assert.equal(clock.paused,false);
assert.equal(clock.advance(35),true,'Resuming uses the remaining time');
clock.resume();assert.equal(clock.active,false,'A completed clock cannot be resumed');
clock.start();clock.pause();clock.cancel();clock.resume();
assert.equal(clock.active,false,'A dismissed feedback form cannot restart its cancelled clock');
assert.equal(clock.paused,false);
console.log('Safety-stop clock: 45 seconds, single completion, cancellation, restart and invalid ticks passed.');
